def text_width(text, glyphs=GLYPHS, scale=1, spacing=1):
    widths = [len(glyphs[c][0]) * scale for c in text]
    return sum(widths) + spacing * scale * (len(widths) - 1)


def draw_glyph(draw: ImageDraw.ImageDraw, x, y, glyph, color, scale=1):
    for row, line in enumerate(glyph):
        for col, cell in enumerate(line):
            if cell == "#":
                draw.rectangle(
                    [x + col * scale, y + row * scale, x + (col + 1) * scale - 1, y + (row + 1) * scale - 1],
                    fill=color,
                )


def draw_text(draw, x, y, text, color, glyphs=GLYPHS, scale=1, spacing=1):
    for c in text:
        draw_glyph(draw, x, y, glyphs[c], color, scale)
        x += (len(glyphs[c][0]) + spacing) * scale

